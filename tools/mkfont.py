# Makes src/ui_font.h: anti-aliased fonts (4-bit coverage per pixel) for the Matrixinator's controls screen.
# Glyphs ' '..'~' from DejaVu Sans Bold at a few pixel sizes. Drawn by ui_font.h's uiText(), blended onto a known background.
from PIL import Image, ImageDraw, ImageFont
import sys
TTF = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
SIZES = {'UI_SMALL': 15, 'UI_MED': 22, 'UI_BIG': 34}
out = ['// Generated by tools/mkfont.py from DejaVu Sans Bold (Bitstream Vera license: free to use and embed). Do not edit.',
       '#pragma once', '#include <stdint.h>',
       'struct UiGlyph { uint32_t off; uint8_t w, h; int8_t dx, dy; uint8_t adv; };   // dy: top of the bitmap, from the baseline (up is negative)',
       'struct UiFont { const uint8_t *bits; const UiGlyph *g; uint8_t ascent, line; };']
for name, px in SIZES.items():
    f = ImageFont.truetype(TTF, px)
    asc, desc = f.getmetrics()
    bits = bytearray(); glyphs = []
    for c in range(32, 127):
        ch = chr(c)
        adv = round(f.getlength(ch))
        bb = f.getbbox(ch)   # relative to the text origin at the top (ascent line)
        if bb[2] <= bb[0] or bb[3] <= bb[1]:
            glyphs.append((len(bits), 0, 0, 0, 0, adv)); continue
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        im = Image.new('L', (w, h), 0); ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=f, fill=255)
        off = len(bits); px4 = [v >> 4 for v in im.getdata()]
        if len(px4) % 2: px4.append(0)
        for i in range(0, len(px4), 2): bits.append((px4[i] << 4) | px4[i + 1])
        glyphs.append((off, w, h, bb[0], bb[1] - asc, adv))
    lo = name.lower()
    out.append(f'static const uint8_t {lo}_bits[] = {{' + ','.join(str(b) for b in bits) + '};')
    out.append(f'static const UiGlyph {lo}_g[] = {{' + ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs) + '};')
    out.append(f'static const UiFont {name} = {{{lo}_bits, {lo}_g, {asc}, {asc + desc}}};')
    print(name, px, 'bytes', len(bits), file=sys.stderr)
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
